function buildSampleExamples() {
  const sampleFiles = readdirSync(sampleDirectory)
    .filter((fileName) => fileName.endsWith("_utf8"))
    .sort();
  const entries = sampleFiles.map((fileName, index) => {
    const sampleContent = readFileSync(join(sampleDirectory, fileName), "utf8");
    const unit = extractRootUnit(sampleContent, fileName);
    const exampleName = fileName.replace(/[^A-Za-z0-9_]/g, "_");

    return [
      exampleName,
      {
        summary: `Definition-only import response from sample/${fileName}`,
        value: {
          statuses: [
            {
              definition: {
                owner: unit.owner,
                customJobType: "",
                registerStatus: "YES",
                rootJobnetName: unit.unitName,
                recoveryUnit: false,
                unitType: unit.unitType,
                unitComment: unit.comment,
                simpleUnitName: unit.simpleUnitName,
                parameters: `sample=${fileName}`,
                execAgent: "",
                execFileName: "",
                wait: false,
                jobnetReleaseUnit: false,
                jp1ResourceGroup: "",
                unitName: unit.unitName,
                unitID: index + 1,
                "x-ajs-butler-sample": `sample/${fileName}`,
              },
              release: null,
              unitStatus: null,
            },
          ],
          all: true,
        },
      },
    ];
  });

  return Object.fromEntries(entries);
}

function extractRootUnit(sampleContent, fileName) {
  const unitMatch = sampleContent.match(/^unit=([^,]+),([^,]*),([^,]*),;/m);
  if (!unitMatch) {
    throw new Error(`Unable to find root unit in sample/${fileName}`);
  }

  const typeMatch = sampleContent.match(/^\s*ty=([^;]+);/m);
  const commentMatch = sampleContent.match(/^\s*cm="([^"]*)";/m);
  const simpleUnitName = unitMatch[1];

  return {
    simpleUnitName,
    unitName: `/${simpleUnitName}`,
    owner: unitMatch[3] || "",
    unitType: mapAjsUnitType(typeMatch?.[1] ?? ""),
    comment: commentMatch?.[1] ?? "",
  };
}

function mapAjsUnitType(unitType) {
  return ajsUnitTypes.get(unitType) ?? unitType.toUpperCase();
}

function renderPrismOpenApi() {
  const prismDocument = structuredClone(document);
  prismDocument.paths["/ajs/api/v1/objects/statuses"].get.responses[
    "200"
  ].content["application/json"].examples = buildSampleExamples();
  prismDocument.info.description = `${document.info.description}

This generated fixture is used by Prism-based tests. Its response examples are
derived from repository samples under sample/.`;

  return `# Generated from docs/specs/features/import-definition-via-webapi/openapi/jp1-ajs3-webapi.v13.openapi.yaml and sample/.
# Do not edit this file directly. Run pnpm run openapi:generate.
${YAML.stringify(prismDocument)}`;
}

const outputs = new Map([
  [infrastructureOutputPath, renderInfrastructureTypes()],
  [testFixtureOutputPath, renderMockFixture()],
  [prismOpenApiOutputPath, renderPrismOpenApi()],
]);

const checkOnly = process.argv.includes("--check");
let hasMismatch = false;

for (const [path, content] of outputs) {
  if (checkOnly) {
    const existing = readFileSync(path, "utf8");
    if (existing !== content) {
      console.error(`Generated artifact is stale: ${path}`);
      hasMismatch = true;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}

if (hasMismatch) {
  process.exitCode = 1;
}
